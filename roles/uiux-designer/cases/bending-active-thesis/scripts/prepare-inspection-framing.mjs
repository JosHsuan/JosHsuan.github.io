// Explicit offline preparation only. Reads the approved public GLB, never CAD or
// private source material. Normal build/runtime do not execute this script.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile, mkdir, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {dirname, resolve} from 'node:path';
import {Vector3} from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {ConvexHull} from 'three/addons/math/ConvexHull.js';
import {sampleSourceSeparation, SOURCE_LAYER_REVISION} from '../components/element-score.mjs';

const outputDirectory = 'D:/JosHsuan_Website/_work/bending-active-thesis/round-04/prepared';
const require = createRequire(import.meta.url);
const threeVersion = JSON.parse(await readFile(resolve(dirname(require.resolve('three')), '../package.json'), 'utf8')).version;
assert.equal(threeVersion, '0.186.1', 'Regeneration requires the reviewed Three version');
const bytes = await readFile(new URL('../release/public/assets/source-layers.glb', import.meta.url));
const metadata = JSON.parse(await readFile(new URL('../release/public/assets/source-layers.json', import.meta.url), 'utf8'));
const hash = value => createHash('sha256').update(value).digest('hex');
assert.equal(hash(bytes), SOURCE_LAYER_REVISION); assert.equal(metadata.revision, SOURCE_LAYER_REVISION);
const gltf = await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
gltf.scene.updateMatrixWorld(true);
try {
  const points = [], roles = [], maxOffsets = sampleSourceSeparation(1).offsets;
  for (const separation of [0, 1]) {
    const offsets = sampleSourceSeparation(separation).offsets;
    gltf.scene.traverse(node => {
      if (!node.isMesh) return;
      const id = node.userData.role, record = metadata.layers.find(layer => layer.id === id);
      assert(record); const positions = node.geometry.attributes.position;
      assert.equal(positions.count, record.vertices);
      assert.equal((node.geometry.index?.count ?? positions.count) / 3, record.triangles);
      if (!separation) {assert(!roles.includes(id)); roles.push(id);}
      const offset = new Vector3(...offsets[id]);
      for (let i = 0; i < positions.count; i++) points.push(new Vector3().fromBufferAttribute(positions, i).applyMatrix4(node.matrixWorld).add(offset));
    });
  }
  assert.equal(roles.length, 3); assert.equal(points.length, metadata.vertices * 2);
  const hull = new ConvexHull().setFromPoints(points), unique = new Map();
  for (const face of hull.faces) {
    let edge = face.edge;
    do {
      const point = edge.head().point.toArray();
      unique.set(point.join(','), point); edge = edge.next;
    } while (edge !== face.edge);
  }
  const support = [...unique.values()].sort((a, b) => a[0] - b[0] || a[1] - b[1] || a[2] - b[2]);
  // JSON number serialization round-trips the original JavaScript doubles. No
  // quantization, decimation or geometric smoothing is performed.
  const serialized = JSON.stringify(support);
  assert.deepEqual(JSON.parse(serialized), support);
  const content = `// Generated by scripts/prepare-inspection-framing.mjs with Three ${threeVersion}.\n`
    + '// Convex support of all approved source vertices at rigid separation 0 and 1.\n'
    + '// Every intermediate layer translation remains inside their convex hull.\n'
    + '// Source geometry is unchanged; points are node-transformed world metres, Y up.\n'
    + 'export const INSPECTION_FRAMING_SUPPORT = Object.freeze({\n'
    + `  sourceSHA256: '${SOURCE_LAYER_REVISION}',\n  sourceVertices: ${metadata.vertices},\n  endpointVertices: ${points.length},\n  hullFaces: ${hull.faces.length},\n`
    + `  maxOffsets: Object.freeze(${JSON.stringify(maxOffsets)}),\n  points: Object.freeze([\n`
    + support.map(point => `    Object.freeze(${JSON.stringify(point)}),`).join('\n')
    + '\n  ]),\n});\n';
  await mkdir(outputDirectory, {recursive: true});
  const outputPath = `${outputDirectory}/inspection-framing-support.mjs`;
  await writeFile(outputPath, content);
  const report = {sourceSHA256: SOURCE_LAYER_REVISION, threeVersion, method: 'ConvexHull over every node-transformed GLB vertex at rigid separation weights 0 and 1; no point quantization or decimation.',
    sourceVertices: metadata.vertices, endpointVertices: points.length, hullFaces: hull.faces.length, supportPoints: support.length,
    maxOffsets, moduleBytes: Buffer.byteLength(content), moduleSHA256: hash(content), outputPath};
  await writeFile(`${outputDirectory}/inspection-framing-support.manifest.json`, JSON.stringify(report, null, 2) + '\n');
  assert.equal(hash(bytes), SOURCE_LAYER_REVISION);
  console.log(JSON.stringify(report, null, 2));
} finally {
  gltf.scene.traverse(node => {node.geometry?.dispose(); if (node.material) (Array.isArray(node.material) ? node.material : [node.material]).forEach(material => material.dispose());});
}
